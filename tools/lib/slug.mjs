const KANA_TABLE = { ...KANA_TO_ROMAJI.hira, ...KANA_TO_ROMAJI.kata };

export function romanizeSlug(input, dict = {}) {
  let out = (input ?? "").toString().trim().toLowerCase();
  if (!out) return "section";

  for (const [k, v] of Object.entries(dict)) {
    out = out.split(k).join(v);
  }

  out = out
    .split("")
    .map((ch) => {
      if (/[a-z0-9-]/.test(ch)) return ch;
      if (KANA_TABLE[ch]) return KANA_TABLE[ch];
      return "_";
    })
    .join("");

  out = out.replace(/-+/g, "-").replace(/_+/g, "_");
  out = out.replace(/^-+|-+$/g, "");
  out = out.replace(/^_+|_+$/g, "");

  return out || "section";
}

export function escapeHtml(s) {
  return (s ?? "")
    .toString()
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}
